export function trData(value, lang = 'vi') {
  if (value == null || lang !== 'en') return value ?? '';
  const text = String(value);
  if (DATA_EN_MAP[text]) return DATA_EN_MAP[text];
  return text
    .replace(/^Bàn\s+/i, 'Table ')
    .replace(/^Mẫu\s*-\s*/i, '')
    .replace(/phần/g, 'items');
}

export function formatTemplate(template, vars = {}) {
  if (typeof template !== 'string') return template || '';
  return template.replace(/\{(\w+)\}/g, (_, key) =>
    vars[key] !== undefined && vars[key] !== null ? String(vars[key]) : ''
  );
}

export function moneyVnd(value, lang = 'vi') {
  const num = Number(value) || 0;
  const formatted = new Intl.NumberFormat(lang === 'en' ? 'en-US' : 'vi-VN', {
    maximumFractionDigits: 0
  }).format(num);
  return lang === 'en' ? `₫${formatted}` : `${formatted}₫`;
}

export function whenLocale(value, lang = 'vi') {
  if (!value) return '—';
  return new Date(value).toLocaleString(lang === 'en' ? 'en-GB' : 'vi-VN', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  });
}

export function clockLocale(value, lang = 'vi') {
  if (!value) return '—';
  return new Date(value).toLocaleTimeString(lang === 'en' ? 'en-GB' : 'vi-VN', {
    hour: '2-digit',
    minute: '2-digit'
  });
}
